import java.util.Properties
import java.io.FileInputStream

val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")

if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

val isReleaseBuild = project.gradle.startParameter.taskNames.any { it.contains("release", ignoreCase = true) }

if (isReleaseBuild && !keystorePropertiesFile.exists()) {
    throw GradleException("Release build requested but key.properties is missing at: ${keystorePropertiesFile.absolutePath}")
}

